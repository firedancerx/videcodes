// ============================================================================
// integrity_guard.cpp — native launch-time self-checksum & anti-tamper engine
// ----------------------------------------------------------------------------
// What it verifies (all fail-closed when compiled with IG_ENFORCE=1):
//   1. SHA-256 of every classes*.dex inside the running base APK
//      (count must match exactly, so an injected classesN.dex also fails).
//   2. SHA-256 of libintegrity_guard.so itself (this file's binary), with its
//      own "expected hashes" blob zeroed before hashing — that is what lets a
//      library carry its own checksum without a chicken-and-egg problem.
//   3. Signing certificate SHA-256, from TWO independent sources:
//        a) DER bytes handed over by Kotlin from PackageManager
//           (GET_SIGNING_CERTIFICATES on API 28+, GET_SIGNATURES below), and
//        b) the APK Signing Block (v2 / v3 / v3.1) parsed straight from the APK
//           file, which defeats Java-level "signature spoofing" hooks.
//   4. Runtime: TracerPid, Debug.isDebuggerConnected(), FLAG_DEBUGGABLE,
//      Frida / Xposed artefacts in /proc/self/maps and thread names.
//
// Expected values live in ONE contiguous, volatile struct (IgBlob) as XOR
// shares: expected = share_a ^ share_b. They are generated by the Gradle task
// :app:printReleaseChecksums into expected_hashes.h.
//
// Build switches
//   IG_ENFORCE=1   release: failures => verdict false, no hash report code.
//   IG_HOST_TEST   compile the pure-C++ core on a desktop for unit testing
//                  (no JNI). See tools/host-test/.
//
// Honest threat model: a native self-check raises the cost of repacking from
// "five minutes in a smali editor" to "reverse-engineer and patch ARM code".
// It does not make the APK un-crackable; nothing client-side can.
// ============================================================================


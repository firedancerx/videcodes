int tracer_pid() {
    int pid = 0;
    for_each_line("/proc/self/status", [&](const std::string& line) {
        static const char kKey[] = "TracerPid:";
        if (line.compare(0, sizeof(kKey) - 1, kKey) == 0) {
            pid = atoi(line.c_str() + sizeof(kKey) - 1);
            return true;
        }
        return false;
    });
    return pid;
}

static bool contains_needle(std::string s, const char* const* needles) {
    for (auto& ch : s) ch = static_cast<char>(tolower(static_cast<unsigned char>(ch)));
    for (const char* const* n = needles; *n; ++n) {
        if (s.find(*n) != std::string::npos) return true;
    }
    return false;
}

bool hook_artifacts_present() {
    static const char* const kMapNeedles[] = {"frida", "gum-js-loop", "xposed", "lsposed",
                                              "substrate", "libsandhook", nullptr};
    static const char* const kThreadNeedles[] = {"gum-js-loop", "pool-frida", "frida", nullptr};
    bool hit = false;
    for_each_line("/proc/self/maps", [&](const std::string& line) {
        hit = contains_needle(line, kMapNeedles);
        return hit;
    });
    if (hit) return true;
    DIR* dir = opendir("/proc/self/task");
    if (!dir) return false;
    while (struct dirent* de = readdir(dir)) {
        if (de->d_name[0] == '.') continue;
        std::string path = std::string("/proc/self/task/") + de->d_name + "/comm";
        for_each_line(path.c_str(), [&](const std::string& line) {
            hit = contains_needle(line, kThreadNeedles);
            return true;
        });
        if (hit) break;
    }
    closedir(dir);
    return hit;
}

bool expected_provisioned() {
    uint8_t exp[32];
    unsplit(g_ig_blob.cert_a, g_ig_blob.cert_b, exp);
    return !is_zero(exp, 32) && g_ig_blob.dex_count > 0;
}

